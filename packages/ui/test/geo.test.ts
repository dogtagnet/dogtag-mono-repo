interface Provider {
  name: string;
  pos: LatLng | null;
}
const posOf = (p: Provider) => p.pos;

describe("sortByDistance", () => {
  const here = P(1.3521, 103.8198); // Singapore
  const near: Provider = { name: "near", pos: P(1.36, 103.83) };
  const mid: Provider = { name: "mid", pos: P(1.5, 104.0) };
  const far: Provider = { name: "far", pos: P(51.5074, -0.1278) };

  it("orders nearest first", () => {
    const out = sortByDistance(here, [far, near, mid], posOf);
    expect(out.map((r) => r.item.name)).toEqual(["near", "mid", "far"]);
    expect(out[0]?.distanceKm).toBeCloseTo(1.434, 2);
  });

  it("puts items with no usable position LAST, with distanceKm null - never 0", () => {
    // The defect this prevents: a null distance compared as 0 ranks every unlocatable provider above
    // every real one, and renders as "0 m away".
    const nowhere: Provider = { name: "nowhere", pos: null };
    const bogus: Provider = { name: "bogus", pos: P(999, 999) };
    const out = sortByDistance(here, [nowhere, far, bogus, near], posOf);
    expect(out.map((r) => r.item.name)).toEqual(["near", "far", "nowhere", "bogus"]);
    expect(out[2]?.distanceKm).toBeNull();
    expect(out[3]?.distanceKm).toBeNull();
    expect(out[0]?.distanceKm).not.toBe(0);
  });

  it("keeps unlocatable items in their input order", () => {
    const a: Provider = { name: "a", pos: null };
    const b: Provider = { name: "b", pos: undefined as unknown as null };
    const c: Provider = { name: "c", pos: P(NaN, NaN) };
    const out = sortByDistance(here, [a, b, c], posOf);
    expect(out.map((r) => r.item.name)).toEqual(["a", "b", "c"]);
  });

  it("is stable for equidistant items", () => {
    const first: Provider = { name: "first", pos: P(2, 103.8198) };
    const second: Provider = { name: "second", pos: P(2, 103.8198) };
    const out = sortByDistance(here, [first, second], posOf);
    expect(out.map((r) => r.item.name)).toEqual(["first", "second"]);
  });

  it("ranks nothing when the ORIGIN is unusable, but still returns every item in input order", () => {
    // The caller still has a list to render; it just has no distances to put on it. That is not an
    // error, and silently dropping the items would be worse than showing them undistanced.
    const out = sortByDistance(P(NaN, NaN), [far, near, mid], posOf);
    expect(out.map((r) => r.item.name)).toEqual(["far", "near", "mid"]);
    expect(out.every((r) => r.distanceKm === null)).toBe(true);
  });

  it("does not mutate the input array", () => {
    const input = [far, near, mid];
    const snapshot = [...input];
    sortByDistance(here, input, posOf);
    expect(input).toEqual(snapshot);
  });

  it("handles an empty list", () => {
    expect(sortByDistance(here, [], posOf)).toEqual([]);
  });

  it("sorts correctly across the antimeridian", () => {
    // A provider 0.1° east of the antimeridian is nearer to one 0.1° west than a provider 5° away on
    // the same side. A raw-longitude sort would invert this.
    const origin = P(0, 179.95);
    const acrossTheLine: Provider = { name: "across", pos: P(0, -179.95) };
    const sameSide: Provider = { name: "sameSide", pos: P(0, 174) };
    const out = sortByDistance(origin, [sameSide, acrossTheLine], posOf);
    expect(out.map((r) => r.item.name)).toEqual(["across", "sameSide"]);
  });
});

