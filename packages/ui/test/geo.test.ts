describe("formatDistanceKm - metric", () => {
  it("uses the sub-10 m floor rather than inventing metre resolution", () => {
    // A GPS fix is good to 5-20 m. "3 m" would be fiction dressed as measurement.
    expect(formatDistanceKm(0)).toBe("< 10 m");
    expect(formatDistanceKm(0.003)).toBe("< 10 m");
    expect(formatDistanceKm(0.0099)).toBe("< 10 m");
  });

  it("rounds to 10 m below a kilometre", () => {
    expect(formatDistanceKm(0.01)).toBe("10 m");
    expect(formatDistanceKm(0.823)).toBe("820 m");
    expect(formatDistanceKm(0.826)).toBe("830 m");
    expect(formatDistanceKm(0.994)).toBe("990 m");
  });

  it("promotes to kilometres when rounding pushes a value out of the metre band", () => {
    // 999 m rounds to 1000, which is a kilometre and should read as one rather than as "1000 m".
    // Same rule as the 9.97 -> "10 km" case: the band is decided after rounding, not before.
    expect(formatDistanceKm(0.999)).toBe("1.0 km");
    expect(formatDistanceKm(0.9999)).toBe("1.0 km");
    expect(formatDistanceKm(0.995)).toBe("1.0 km");
  });

  it("never shows more precision than it has", () => {
    // The claim under test: no output carries a digit finer than 10 m / 0.1 km / 1 km for its band.
    expect(formatDistanceKm(0.8231)).toBe("820 m");
    expect(formatDistanceKm(3.4499)).toBe("3.4 km");
    expect(formatDistanceKm(27.49)).toBe("27 km");
  });

  it("shows one decimal from 1 to 10 km", () => {
    expect(formatDistanceKm(1)).toBe("1.0 km");
    expect(formatDistanceKm(3.44)).toBe("3.4 km");
    expect(formatDistanceKm(9.94)).toBe("9.9 km");
  });

  it("shows whole kilometres at and above 10", () => {
    expect(formatDistanceKm(10)).toBe("10 km");
    expect(formatDistanceKm(27.4)).toBe("27 km");
    expect(formatDistanceKm(10847.8)).toBe("10848 km");
  });

  it("does not print a trailing zero it did not measure at the band edge", () => {
    // 9.97 rounds to 10.0, which must render as "10 km" rather than "10.0 km".
    expect(formatDistanceKm(9.97)).toBe("10 km");
  });
});

