describe("encodeGeohash", () => {
  it("matches the published reference vectors", () => {
    // The canonical example from the original geohash.org write-up.
    expect(encodeGeohash(57.64911, 10.40744, 11)).toBe("u4pruydqqvj");
    // The widely-cited Curitiba vector.
    expect(encodeGeohash(-25.382708, -49.265506, 12)).toBe("6gkzwgjzn820");
  });

  it("agrees with an independent decode of its own output", () => {
    // Not a published vector - a self-check, and it is here because a published literal is only as
    // good as the coordinates it was published WITH. A commonly-quoted Eiffel Tower hash
    // ("u09tunquc") decodes to 48.858411, 2.294490, which is a few tens of metres from the
    // 48.858093, 2.294694 usually printed beside it; asserting that pair would have failed a correct
    // encoder. So this pins the round trip instead, which is checkable from first principles.
    const hash = encodeGeohash(48.858093, 2.294694, 9);
    expect(hash).toBe("u09tunqgn");
    const cell = decodeGeohash(hash);
    expect(cell).not.toBeNull();
    if (!cell) return;
    expect(geohashCellContains(cell, P(48.858093, 2.294694))).toBe(true);
  });

  it("is a strict prefix chain - shortening a hash always coarsens the same cell", () => {
    const full = encodeGeohash(1.3521, 103.8198, 10);
    expect(full).not.toBeNull();
    for (let p = 1; p <= 10; p += 1) {
      expect(encodeGeohash(1.3521, 103.8198, p)).toBe(full?.slice(0, p));
    }
  });

  it("uses only the geohash alphabet", () => {
    for (let i = 0; i < 200; i += 1) {
      const h = encodeGeohash(-90 + (180 * i) / 200, -180 + (360 * i) / 200, 9);
      expect(h).not.toBeNull();
      for (const ch of h ?? "") expect(GEOHASH_BASE32).toContain(ch);
    }
  });

  it("handles the extremes of the coordinate space", () => {
    for (const [lat, lng] of [
      [0, 0], [90, 180], [-90, -180], [90, -180], [-90, 180], [0, 180], [0, -180],
    ] as const) {
      const h = encodeGeohash(lat, lng, 9);
      expect(h, `${lat},${lng}`).not.toBeNull();
      expect(h).toHaveLength(9);
    }
  });

  it("returns null rather than a hash of something that was never a place", () => {
    expect(encodeGeohash(NaN, 0, 5)).toBeNull();
    expect(encodeGeohash(0, Infinity, 5)).toBeNull();
    expect(encodeGeohash(91, 0, 5)).toBeNull();
    expect(encodeGeohash(0, 181, 5)).toBeNull();
  });

  it("rejects an out-of-range or non-integer precision", () => {
    expect(encodeGeohash(0, 0, 0)).toBeNull();
    expect(encodeGeohash(0, 0, -1)).toBeNull();
    expect(encodeGeohash(0, 0, 2.5)).toBeNull();
    expect(encodeGeohash(0, 0, MAX_GEOHASH_PRECISION + 1)).toBeNull();
    expect(encodeGeohash(0, 0, MAX_GEOHASH_PRECISION)).toHaveLength(MAX_GEOHASH_PRECISION);
  });
});

describe("decodeGeohash", () => {
  it("returns a CELL, and the original point lies inside it", () => {
    // The property that makes the return type honest: decode does not recover the point, it recovers
    // the box the point was in.
    const point = P(1.3521, 103.8198);
    for (const precision of [1, 3, 5, 7, 9]) {
      const hash = encodeGeohash(point.lat, point.lng, precision);
      const cell = decodeGeohash(hash);
      expect(cell, `precision ${precision}`).not.toBeNull();
      if (!cell) continue;
      expect(geohashCellContains(cell, point)).toBe(true);
      expect(cell.precision).toBe(precision);
    }
  });

  it("reports the cell's real size, so the error is visible at the call site", () => {
    // The scouting report's figures: geohash-4 is ~39 x 19.5 km, geohash-5 ~4.9 km square.
    const c4 = decodeGeohash(encodeGeohash(0, 0, 4));
    expect(c4?.widthKm).toBeCloseTo(39.1, 0);
    expect(c4?.heightKm).toBeCloseTo(19.6, 0);

    const c5 = decodeGeohash(encodeGeohash(0, 0, 5));
    expect(c5?.widthKm).toBeCloseTo(4.9, 0);
    expect(c5?.heightKm).toBeCloseTo(4.9, 0);
  });

  it("reports a NARROWER cell at high latitude, because longitude converges", () => {
    // Why width is computed rather than read from a table: the same precision is a much narrower box
    // near the poles. A caller reasoning about disclosure needs the real number.
    const equator = decodeGeohash(encodeGeohash(0, 0, 4));
    const north = decodeGeohash(encodeGeohash(75, 0, 4));
    expect(north?.widthKm).toBeLessThan((equator?.widthKm ?? 0) / 3);
    // Height does not change - only longitude converges.
    expect(north?.heightKm).toBeCloseTo(equator?.heightKm ?? 0, 1);
  });

  it("centre is the middle of the box, and is up to half a cell from the true point", () => {
    const point = P(1.3521, 103.8198);
    const cell = decodeGeohash(encodeGeohash(point.lat, point.lng, 4));
    expect(cell).not.toBeNull();
    if (!cell) return;
    expect(cell.center.lat).toBeCloseTo((cell.lat.min + cell.lat.max) / 2, 12);
    expect(cell.center.lng).toBeCloseTo((cell.lng.min + cell.lng.max) / 2, 12);
    // The error a `decode -> {lat,lng}` signature would have hidden: kilometres, not metres.
    const err = haversineKm(point, cell.center);
    expect(err).toBeGreaterThan(1);
    expect(err).toBeLessThanOrEqual(Math.hypot(cell.widthKm, cell.heightKm) / 2 + 1e-6);
  });

  it("round-trips: re-encoding a cell's centre reproduces its hash", () => {
    for (const hash of ["u4pruydqqvj", "6gkz", "ezs42", "s", "gbsuv"]) {
      const cell = decodeGeohash(hash);
      expect(cell, hash).not.toBeNull();
      if (!cell) continue;
      expect(encodeGeohash(cell.center.lat, cell.center.lng, hash.length)).toBe(hash);
    }
  });

  it("is case-insensitive", () => {
    expect(decodeGeohash("U4PRUYDQQVJ")?.hash).toBe("u4pruydqqvj");
    expect(decodeGeohash("U4PRUYDQQVJ")?.center).toEqual(decodeGeohash("u4pruydqqvj")?.center);
  });

  it("returns null for an undecodable hash rather than a plausible wrong box", () => {
    expect(decodeGeohash("")).toBeNull();
    expect(decodeGeohash(null)).toBeNull();
    expect(decodeGeohash(undefined)).toBeNull();
    // `a`, `i`, `l`, `o` are excluded from the alphabet.
    expect(decodeGeohash("abc")).toBeNull();
    expect(decodeGeohash("u4pri")).toBeNull();
    expect(decodeGeohash("u4pr!")).toBeNull();
    expect(decodeGeohash(" u4pr")).toBeNull();
    expect(decodeGeohash("u".repeat(MAX_GEOHASH_PRECISION + 1))).toBeNull();
  });

  it("contains a point at the very top of the coordinate domain", () => {
    // The bug this pins: a strictly half-open rule leaves lat 90 and lng 180 in NO cell, because
    // there is no neighbour above them to own the edge. So `contains(decode(encode(p)), p)` was
    // false for the north pole and for every point on the +180 antimeridian - a point not inside
    // its own cell.
    for (const [lat, lng] of [
      [90, 180], [90, 0], [90, -73], [0, 180], [45, 180], [-90, 180], [90, -180],
    ] as const) {
      const cell = decodeGeohash(encodeGeohash(lat, lng, 4));
      expect(cell, `${lat},${lng}`).not.toBeNull();
      if (!cell) continue;
      expect(geohashCellContains(cell, P(lat, lng)), `${lat},${lng} not in its own cell`).toBe(true);
    }
  });

  it("contains a point at the bottom of the domain too, which always worked", () => {
    // The min edges are inclusive, which is why -90/-180 passed and hid the case above.
    for (const [lat, lng] of [[-90, -180], [-90, 0], [0, -180]] as const) {
      const cell = decodeGeohash(encodeGeohash(lat, lng, 4));
      expect(cell).not.toBeNull();
      if (!cell) continue;
      expect(geohashCellContains(cell, P(lat, lng)), `${lat},${lng}`).toBe(true);
    }
  });

  it("closing the top edge does not make cells overlap", () => {
    // The fix must not break tiling. A point on an INTERIOR max edge still belongs to exactly one
    // cell - the one above it - so only the domain boundary is closed.
    const cell = decodeGeohash("u4pr");
    expect(cell).not.toBeNull();
    if (!cell) return;
    expect(cell.lat.max).not.toBe(90);
    expect(cell.lng.max).not.toBe(180);
    // Its own top-edge points belong to the NEXT cell, not to it.
    expect(geohashCellContains(cell, P(cell.lat.max, cell.center.lng))).toBe(false);
    expect(geohashCellContains(cell, P(cell.center.lat, cell.lng.max))).toBe(false);
  });

  it("every point belongs to exactly one cell across a sweep that includes the boundaries", () => {
    // An exhaustive one-cell-only check over a coarse precision, boundaries included. Precision 2
    // keeps the cell count small enough to enumerate all of them per point.
    const allHashes: string[] = [];
    for (const a of GEOHASH_BASE32) for (const b of GEOHASH_BASE32) allHashes.push(a + b);
    const cells = allHashes.map((h) => decodeGeohash(h)).filter((c): c is NonNullable<typeof c> => !!c);
    expect(cells).toHaveLength(1024);

    for (const [lat, lng] of [
      [90, 180], [-90, -180], [90, -180], [-90, 180], [0, 0], [0, 180], [0, -180],
      [90, 0], [-90, 0], [51.5074, -0.1278], [1.3521, 103.8198], [-33.86, 151.21],
    ] as const) {
      const hits = cells.filter((c) => geohashCellContains(c, P(lat, lng)));
      expect(hits, `${lat},${lng} landed in ${hits.length} cells`).toHaveLength(1);
      // And it is the cell `encodeGeohash` names.
      expect(hits[0]?.hash).toBe(encodeGeohash(lat, lng, 2));
    }
  });

  it("cells at one precision tile the globe without gaps or overlaps", () => {
    // `geohashCellContains` is inclusive-min / exclusive-max so adjacent cells abut exactly. If it
    // were inclusive on both, a point on a boundary would be in two cells.
    for (let i = 0; i < 300; i += 1) {
      const point = P(-89 + (178 * i) / 300, -179 + (358 * ((i * 7) % 300)) / 300);
      const own = decodeGeohash(encodeGeohash(point.lat, point.lng, 4));
      expect(own).not.toBeNull();
      if (!own) continue;
      expect(geohashCellContains(own, point)).toBe(true);
    }
  });
});

describe("geohash - the coarsening property later slices depend on", () => {
  it("a shorter prefix names a strictly larger cell containing the longer one", () => {
    const fine = decodeGeohash("u4pruyd");
    const coarse = decodeGeohash("u4pr");
    expect(fine).not.toBeNull();
    expect(coarse).not.toBeNull();
    if (!fine || !coarse) return;
    expect(coarse.widthKm).toBeGreaterThan(fine.widthKm);
    expect(coarse.heightKm).toBeGreaterThan(fine.heightKm);
    expect(fine.lat.min).toBeGreaterThanOrEqual(coarse.lat.min);
    expect(fine.lat.max).toBeLessThanOrEqual(coarse.lat.max);
    expect(fine.lng.min).toBeGreaterThanOrEqual(coarse.lng.min);
    expect(fine.lng.max).toBeLessThanOrEqual(coarse.lng.max);
  });

  it("two nearby points share a coarse prefix but differ at fine precision", () => {
    // The basis of prefix sharding - and the reason sharding leaks: sharing a prefix IS revealing
    // the cell you are in.
    const a = P(1.3521, 103.8198);
    const b = P(1.3555, 103.8225);
    expect(encodeGeohash(a.lat, a.lng, 4)).toBe(encodeGeohash(b.lat, b.lng, 4));
    expect(encodeGeohash(a.lat, a.lng, 9)).not.toBe(encodeGeohash(b.lat, b.lng, 9));
  });
});
