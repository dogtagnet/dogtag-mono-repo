describe("initialBearingDeg - the cardinal directions", () => {
  it("reads N / E / S / W from the equator", () => {
    expect(initialBearingDeg(P(0, 0), P(1, 0))).toBeCloseTo(0, 6);
    expect(initialBearingDeg(P(0, 0), P(0, 1))).toBeCloseTo(90, 6);
    expect(initialBearingDeg(P(0, 0), P(-1, 0))).toBeCloseTo(180, 6);
    expect(initialBearingDeg(P(0, 0), P(0, -1))).toBeCloseTo(270, 6);
  });

  it("is always in [0, 360)", () => {
    for (let i = 0; i < 720; i += 1) {
      const b = initialBearingDeg(P(0, 0), P(Math.sin(i) * 45, Math.cos(i) * 90));
      if (b === null) continue;
      expect(b).toBeGreaterThanOrEqual(0);
      expect(b).toBeLessThan(360);
    }
  });

  it("returns 0 rather than 360 for due north", () => {
    // `(-0 + 360) % 360` is 0; without the second modulo this would be 360 and fall outside range.
    expect(initialBearingDeg(P(-10, 5), P(10, 5))).toBe(0);
  });

  it("reads correctly across the antimeridian", () => {
    // Going from 179.9 to -179.9 is EAST (bearing ~90), not west.
    const b = initialBearingDeg(P(0, 179.9), P(0, -179.9));
    expect(b).toBeCloseTo(90, 3);
  });

  it("points due north toward the north pole from anywhere", () => {
    // The DESTINATION being a pole is not degenerate.
    expect(initialBearingDeg(P(45, 12), P(90, 0))).toBeCloseTo(0, 6);
    expect(initialBearingDeg(P(-30, -170), P(90, 88))).toBeCloseTo(0, 6);
    expect(initialBearingDeg(P(45, 12), P(-90, 0))).toBeCloseTo(180, 6);
  });
});

describe("initialBearingDeg - the undefined cases return null, never a direction", () => {
  it("identical points", () => {
    // `atan2(0, 0)` is 0, which renders as "N" - a heading manufactured from nothing.
    expect(initialBearingDeg(P(0, 0), P(0, 0))).toBeNull();
    expect(initialBearingDeg(P(51.5074, -0.1278), P(51.5074, -0.1278))).toBeNull();
  });

  it("an origin at a pole, where north is not a direction", () => {
    expect(initialBearingDeg(P(90, 0), P(0, 0))).toBeNull();
    expect(initialBearingDeg(P(-90, 0), P(0, 0))).toBeNull();
    // The specific wrong answer this prevents: at the north pole the formula reports "east" for a
    // target 90° of longitude away, when in truth every direction from there is south.
    expect(initialBearingDeg(P(90, 0), P(0, 90))).toBeNull();
  });

  it("unusable coordinates on either side", () => {
    expect(initialBearingDeg(P(NaN, 0), P(0, 0))).toBeNull();
    expect(initialBearingDeg(P(0, 0), P(0, NaN))).toBeNull();
    expect(initialBearingDeg(P(0, 0), P(91, 0))).toBeNull();
  });

});

describe("initialBearingDeg - antipodes are ambiguous but NOT undefined", () => {
  it("returns a heading that really does reach the destination", () => {
    // Deliberately not `null`. Between antipodes every great circle is a shortest path, so the
    // bearing is not unique - but due east along the equator genuinely reaches (0, 180), so 90 is
    // one of several right answers rather than a manufactured one. That is a different situation
    // from identical points, where no path exists at all and `atan2(0, 0)` would print "N".
    const b = initialBearingDeg(P(0, 0), P(0, 180));
    expect(b).not.toBeNull();
    expect(b).toBeCloseTo(90, 6);
  });

  it("still refuses when the ambiguity is compounded by a degenerate origin", () => {
    // Pole-to-pole is antipodal AND origin-at-a-pole. The pole rule wins.
    expect(initialBearingDeg(P(90, 0), P(-90, 0))).toBeNull();
  });
});

describe("compass rendering", () => {
  it("maps the eight points", () => {
    const expected: Array<[number, string]> = [
      [0, "N"], [45, "NE"], [90, "E"], [135, "SE"],
      [180, "S"], [225, "SW"], [270, "W"], [315, "NW"],
    ];
    for (const [deg, label] of expected) expect(compassPoint8(deg)).toBe(label);
  });

  it("wraps 360 back to N rather than off the end of the rose", () => {
    // The index is `round(deg / 45)`, which is 8 at 360 - one past the end of an 8-element array.
    // Without the trailing `% 8` this would be `undefined`.
    expect(compassPoint8(360)).toBe("N");
    expect(compassPoint8(359)).toBe("N");
    expect(compassPoint8(330)).toBe("NW");
    expect(compassPoint16(360)).toBe("N");
    expect(compassPoint16(349)).toBe("N");
  });

  it("rounds half away from the origin at a sector boundary, consistently", () => {
    // 337.5 is exactly the NW/N boundary. `Math.round` is half-up, so it lands on N. Pinned because
    // it is the kind of edge a refactor silently flips, not because either answer is wrong.
    expect(compassPoint8(337.5)).toBe("N");
    expect(compassPoint8(337.4)).toBe("NW");
    expect(compassPoint8(22.5)).toBe("NE");
    expect(compassPoint8(22.4)).toBe("N");
  });

  it("accepts out-of-range degrees by normalising rather than returning nothing", () => {
    expect(compassPoint8(450)).toBe("E");
    expect(compassPoint8(-90)).toBe("W");
    expect(compassPoint16(-22.5)).toBe("NNW");
  });

  it("maps the sixteen points at their boundaries", () => {
    expect(compassPoint16(0)).toBe("N");
    expect(compassPoint16(22.5)).toBe("NNE");
    expect(compassPoint16(45)).toBe("NE");
    expect(compassPoint16(202.5)).toBe("SSW");
    expect(compassPoint16(292.5)).toBe("WNW");
  });

  it("propagates null so a caller can never print a direction that was not established", () => {
    expect(compassPoint8(null)).toBeNull();
    expect(compassPoint16(null)).toBeNull();
    expect(compassPoint8(NaN)).toBeNull();
    expect(compassPoint16(Infinity)).toBeNull();
  });

  it("composes with a null bearing end-to-end", () => {
    expect(compassPoint8(initialBearingDeg(P(5, 5), P(5, 5)))).toBeNull();
  });
});

