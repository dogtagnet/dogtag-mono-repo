/**
 * The on-device geo core.
 *
 * The properties that actually matter, and the reason each is here rather than being a rounding
 * quibble:
 *
 *   * NO INPUT MAY YIELD NaN. A NaN distance collapses to `false` in a radius filter, so a "could
 *     not compute" would render as a definite "out of range" - exactly the class of over-claim this
 *     codebase removes everywhere else. That is the whole reason the implementation uses `atan2`
 *     rather than the `asin` form the deprecated server filter uses.
 *   * AN UNDEFINED ANSWER IS `null`, NEVER A PLAUSIBLE NUMBER. Bearing between identical points is
 *     the sharp one: `atan2(0, 0)` is `0`, which a caller prints as "N".
 *   * THE ANTIMERIDIAN AND THE POLES ARE ORDINARY. Both are where naive implementations produce
 *     answers that are wrong by half a planet while looking perfectly well-formed.
 *
 * Cross-language parity with the deprecated server filter lives in `geoParity.test.ts`, against a
 * fixture generated by the Rust itself.
 */

const P = (lat: number, lng: number): LatLng => ({ lat, lng });

/**
 * The naive equirectangular approximation, present ONLY as a foil.
 *
 * It treats a degree of longitude as a constant width, which is true at the equator and increasingly
 * false toward the poles. Several tests below assert the real implementation does NOT agree with it,
 * because "distance" implementations that quietly do this are common and the failure is invisible at
 * the equator where people test.
 */
const equirectangularKm = (a: LatLng, b: LatLng): number => {
  const dLat = ((b.lat - a.lat) * Math.PI) / 180;
  const dLng = ((b.lng - a.lng) * Math.PI) / 180;
  return Math.hypot(dLat, dLng) * EARTH_RADIUS_KM;
};

